    def create(self, code: int, *args) -> None:
        char = []
        for num in args:
            line = bin(num)[2:].zfill(8)[::-1]
            bool_line = [(i == '1') for i in line]
            char.append(bool_line)
        self._chars[code] = char

    def get_char(self, code: int) -> list[list[bool]]:
        ch = self._chars.get(code, self._chars[0])
        result = [i.copy() for i in ch]
        return result
